    private void btnLogOnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLogOnActionPerformed
    String userType = (String) cmbUserType.getSelectedItem();
    String username = txfUsername.getText();
    String password = new String(pwfPassword.getPassword());
    lblError.setText("");

    if (userType.equals("Administrator")) {
        checkAdministrator(username, password);
    } else if (userType.equals("Member")) {
        checkMember(username, password);
    }
}//GEN-LAST:event_btnLogOnActionPerformed

private void checkAdministrator(String username, String password) {
    int pos = Manager.userArray.searchUserName(username);
    if (pos == -1) {
        lblError.setText("User not found");
        return;
    }
    User user = Manager.userArray.getUser(pos);
    if (user.getPassword().equals(password) && user.getUserType().equals("Administrator")) {
        Manager.currentUser = pos;
        new MainGUI().setVisible(true);
        this.dispose();
    } else {
        lblError.setText("Incorrect username or password");
        txfUsername.setText("");
        pwfPassword.setText("");
    }
}

private void checkMember(String username, String password) {
    int pos = Manager.userArray.searchUserName(username);
    if (pos == -1) {
        lblError.setText("User not found");
        return;
    }
    User user = Manager.userArray.getUser(pos);
    if (user.getPassword().equals(password) && user.getUserType().equals("Member")) {
        Manager.currentUser = pos;
        new MainGUI().setVisible(true);
        this.dispose();
    } else {
        lblError.setText("Incorrect username or password");
        txfUsername.setText("");
        pwfPassword.setText("");
    }
}

